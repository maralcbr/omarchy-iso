# Apple Silicon WiFi/Bluetooth firmware is machine-specific and cannot ship in
# the OS image. The installer leaves it in the EFI system partition, and the
# upstream initramfs hook only exposes it through a symlink that depends on the
# bootloader passing an ESP pointer. When that link breaks the driver silently
# has no firmware and wireless never comes up, so install a real copy into
# /lib/firmware instead of depending on the boot-time reference.
#
# Both radios probe early in boot, before this unit has extracted the
# firmware, so both must be reloaded afterwards. Reloading only brcmfmac left
# the first boot after an install with working Wi-Fi and dead Bluetooth:
# hci_bcm4377 had already failed with "Unable to load firmware" at ~4.5 s.
VENDOR_FIRMWARE_UNIT = """\
[Unit]
Description=Install Apple vendor firmware into /lib/firmware
After=local-fs.target
ConditionPathExists=/boot/efi/vendorfw/firmware.tar

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/bin/sh -c 'set -e; src=/boot/efi/vendorfw/firmware.tar; stamp=/var/lib/omarchy/vendor-firmware.stamp; if [ ! -f "$stamp" ] || [ "$src" -nt "$stamp" ]; then install -d -m 0755 /lib/firmware /var/lib/omarchy; tar -xf "$src" -C /lib/firmware; touch -r "$src" "$stamp"; fi'
ExecStartPost=-/usr/bin/sh -c 'for m in brcmfmac hci_bcm4377; do modprobe -r "$m" 2>/dev/null || true; modprobe "$m" 2>/dev/null || true; done'

[Install]
WantedBy=multi-user.target
"""


def install_vendor_firmware(ctx: InstallContext) -> None:
    """Persist the machine's vendor firmware into the installed system."""
    info("\u203a installing vendor firmware service")
    unit = ctx.target / "etc" / "systemd" / "system" / "omarchy-vendor-firmware.service"
    unit.parent.mkdir(parents=True, exist_ok=True)
    unit.write_text(VENDOR_FIRMWARE_UNIT)
    subprocess.run(
        ["arch-chroot", str(ctx.target), "systemctl", "enable",
         "omarchy-vendor-firmware.service"],
        check=True,
    )


